// 사용자가 입력한 값을 화면에 넣기 전에 감싸는 함수.
//
// 이 앱들은 innerHTML + 템플릿 문자열로 화면을 그린다. 회원이 입력한 값을
// 그대로 넣으면 그 자리에서 코드가 실행된다. 실제로 회원 이름이 관리자
// 화면에서 실행되는 취약점이 있었다.
//
// CSP 의 script-src 를 아직 조이지 못했으므로 이것이 유일한 방어선이다.
// 그래서 세 앱에 흩어져 있던 사본을 한곳으로 모았다. 여기를 고치면
// 세 앱에 한꺼번에 적용된다.
//
// 코치앱 사본은 replaceAll 을 쓰고 작은따옴표를 &#039; 로 냈다. 감싸는
// 글자는 같고 &#39; 와 &#039; 는 둘 다 작은따옴표로 렌더된다. 회원앱·관리자
// 쪽으로 통일했다.
//
// ⚠ IIFE 로 감싸지 않는다. 전역 함수 선언 그대로여야 세 앱의 호출부를
// 한 줄도 안 바꾼다.

function escapeHtml(value = "") {
  return String(value).replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#39;",
  })[char]);
}
